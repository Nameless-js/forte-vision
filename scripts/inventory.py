"""Inventory all videos with PyAV (duration, fps, resolution, codec, frame count, size, md5).

Writes analysis/inventory.md and data/inventory.csv.
Usage: python scripts/inventory.py [--videos public] [--labels data/labels.csv]
"""

from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from forte_ai.labels import parse_video_id, read_labels_csv  # noqa: E402


def probe(path: Path) -> dict:
    import av

    with av.open(str(path)) as c:
        vs = c.streams.video[0]
        fps = float(vs.average_rate or vs.guessed_rate or 0)
        if c.duration:
            dur = float(c.duration / av.time_base)
        elif vs.duration:
            dur = float(vs.duration * vs.time_base)
        else:
            dur = 0.0
        rotation = ""
        try:
            rotation = str(dict(vs.metadata or {}).get("rotate", ""))
        except Exception:
            pass
        info = {
            "file": path.name,
            "video_id": parse_video_id(path.name),
            "duration_s": round(dur, 3),
            "fps": round(fps, 3),
            "width": vs.codec_context.width,
            "height": vs.codec_context.height,
            "codec": vs.codec_context.name,
            "pix_fmt": vs.codec_context.pix_fmt,
            "nb_frames": vs.frames,
            "n_streams": len(c.streams),
            "has_audio": len(c.streams.audio) > 0,
            "size_mb": round(path.stat().st_size / 1e6, 2),
            "rotation": rotation,
        }
    return info


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--videos", default=str(ROOT / "public"))
    ap.add_argument("--labels", default=str(ROOT / "data" / "labels.csv"))
    ap.add_argument("--out-md", default=str(ROOT / "analysis" / "inventory.md"))
    ap.add_argument("--out-csv", default=str(ROOT / "data" / "inventory.csv"))
    a = ap.parse_args()

    labels = {r.video_id: r for r in read_labels_csv(Path(a.labels))} if Path(a.labels).exists() else {}
    rows = []
    for p in sorted(Path(a.videos).iterdir(), key=lambda p: parse_video_id(p.name) or 0):
        if p.suffix.lower() not in (".mov", ".mp4"):
            continue
        info = probe(p)
        lr = labels.get(info["video_id"])
        info["label"] = lr.label if lr else ""
        info["t_label"] = "" if (lr is None or lr.t_sec is None) else lr.t_sec
        info["content_md5"] = lr.content_md5 if lr else ""
        rows.append(info)

    Path(a.out_csv).parent.mkdir(parents=True, exist_ok=True)
    with open(a.out_csv, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    durs = [r["duration_s"] for r in rows]
    fpss = sorted({r["fps"] for r in rows})
    ress = sorted({f'{r["width"]}x{r["height"]}' for r in rows})
    codecs = sorted({r["codec"] for r in rows})
    n_viol = sum(1 for r in rows if r["label"] == "violation")
    n_clean = sum(1 for r in rows if r["label"] == "no_violation")
    longest = sorted(rows, key=lambda r: -r["duration_s"])[:3]
    md = []
    md.append("# Video inventory\n")
    md.append(
        f"Generated by `scripts/inventory.py` with PyAV. {len(rows)} files in `{Path(a.videos).name}/`, "
        f"total {sum(r['size_mb'] for r in rows):.0f} MB, total duration {sum(durs):.0f} s.\n"
    )
    md.append(f"- duration: min {min(durs):.1f} s, median {sorted(durs)[len(durs) // 2]:.1f} s, max {max(durs):.1f} s")
    md.append(f"- fps values: {fpss}")
    md.append(f"- resolutions: {ress}")
    md.append(f"- codecs: {codecs}; audio streams present: {any(r['has_audio'] for r in rows)}")
    md.append(f"- rotation metadata: {sorted({r['rotation'] for r in rows})}")
    md.append(f"- labels joined: {n_viol} violation, {n_clean} clean, {len(rows) - n_viol - n_clean} unlabeled")
    md.append(
        "- 3 longest videos (timing benchmark): "
        + ", ".join(f"{r['file']} ({r['duration_s']:.1f} s)" for r in longest)
    )
    md.append("")
    md.append("| id | file | label | t_label | duration s | fps | WxH | codec | frames | MB | md5 |")
    md.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        t = r["t_label"] if r["t_label"] != "" else "-"
        md.append(
            f"| {r['video_id']} | {r['file']} | {r['label'] or '-'} | {t} | {r['duration_s']:.2f} | {r['fps']} | "
            f"{r['width']}x{r['height']} | {r['codec']} | {r['nb_frames']} | {r['size_mb']} | {r['content_md5'][:8]} |"
        )
    Path(a.out_md).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out_md).write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md[:10]))
    print(f"wrote {a.out_md} and {a.out_csv}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
