import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {createRequire} from 'node:module';
const bundle = await build({entryPoints:['src/components/ui/dropdown-scroll.ts'],bundle:true,write:false,platform:'node',format:'cjs'});
const module = {exports:{}};
new Function('require','module','exports',bundle.outputFiles[0].text)(createRequire(import.meta.url),module,module.exports);
const {revealDropdownOption} = module.exports;
const option = {offsetTop:0,offsetHeight:36,scrollIntoView(){throw new Error('Must never scroll page ancestors');}};
const menu = {scrollTop:0,clientHeight:120,querySelector:()=>option};
revealDropdownOption(menu,0);
assert.equal(menu.scrollTop,0,'First visible option must not scroll');
option.offsetTop=240;
revealDropdownOption(menu,6);
assert.equal(menu.scrollTop,156,'Only the menu scrolls to an option below its viewport');
option.offsetTop=36;
revealDropdownOption(menu,1);
assert.equal(menu.scrollTop,36,'Only the menu scrolls back up');
option.offsetTop=72;
revealDropdownOption(menu,2);
assert.equal(menu.scrollTop,36,'Already visible options leave scroll unchanged');
menu.querySelector=()=>null;
revealDropdownOption(menu,99);
assert.equal(menu.scrollTop,36,'Missing options leave scroll unchanged');
console.log('PASS dropdown opening and keyboard navigation scroll only the menu');
